let currentLanguage = "en";
const listeners = new Set();

export const i18n = {
  changeLanguage: (lng) => {
    if (resources[lng]) {
      currentLanguage = lng;
      listeners.forEach(cb => cb(lng));
    }
  },
  language: currentLanguage
};

export function useTranslation() {
  const [lang, setLang] = useState(currentLanguage);
  
  useEffect(() => {
    const cb = (newLang) => setLang(newLang);
    listeners.add(cb);
    return () => listeners.delete(cb);
  }, []);

  const t = (key) => {
    const translations = resources[lang] || resources["en"];
    return translations[key] || resources["en"][key] || key;
  };

  return { t, i18n };
}
